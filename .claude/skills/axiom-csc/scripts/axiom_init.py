#!/usr/bin/env python3
import pathlib, re, sys

SCAN_EXT = {".py",".ts",".js",".yaml",".yml",".json",".env",".toml"}
HEURISTICS = [
    ("transaction_value", r'(?:max|limit|cap).*?(?:amount|price|cost|invoice)[^\n]*?(\d[\d,]*(?:\.\d{2})?)', "lte", 10000, "BLOCK"),
    ("rate_limit_rpm",    r'(?:rate.?limit|throttle|rpm)[^\n]*?(\d+)', "lte", 1000, "BLOCK"),
    ("file_size_mb",      r'(?:max.?(?:file)?size|upload.?limit)[^\n]*?(\d+)\s*MB', "lte", 100, "BLOCK"),
    ("query_row_limit",   r'LIMIT\s+(\d+)', "lte", 10000, "BLOCK"),
    ("api_quota_daily",   r'(?:daily.?(?:quota|limit)|calls?.?per.?day)[^\n]*?(\d+)', "required", None, "ASK"),
    ("retry_count",       r'(?:max.?retries?|retry.?count)[^\n]*?(\d+)', "lte", 5, "BLOCK"),
]

def scan(root):
    findings = {}
    for path in pathlib.Path(root).rglob("*"):
        if path.suffix not in SCAN_EXT: continue
        if any(p in path.parts for p in (".git","node_modules","__pycache__",".venv")): continue
        try: text = path.read_text(errors="ignore")
        except: continue
        for concept, pattern, op, default, action in HEURISTICS:
            m = re.search(pattern, text, re.IGNORECASE)
            if m and concept not in findings:
                try: val = float(m.group(1).replace(",",""))
                except: val = default
                findings[concept] = (val, str(path.relative_to(root)), op, action)
    return findings

def gen_yaml(findings):
    lines = ["# .axiom/invariants.yaml — generated by axiom init","version: '1.0'","mode: STRICT","","rules:"]
    for concept, (val, src, op, action) in findings.items():
        lines.append(f"  # detected in: {src}")
        lines.append(f"  - concept: {concept}")
        if action == "ASK":
            lines.append(f"    required: true")
            lines.append(f"    action_on_missing: ASK")
        else:
            lines.append(f"    op: {op}")
            lines.append(f"    value: {val}")
            lines.append(f"    action_on_fail: BLOCK")
        lines.append("")
    if "role_assignment" not in findings:
        lines += ["  # auth — always required","  - concept: role_assignment","    required: true","    action_on_missing: ASK",""]
    return "\n".join(lines)

if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    print(f"[axiom init] Scanning {pathlib.Path(root).resolve()} ...")
    findings = scan(root)
    print(f"[axiom init] Signals found: {list(findings.keys()) or ['(none)']} + role_assignment (always)")
    out = pathlib.Path(root) / ".axiom" / "invariants.yaml"
    out.parent.mkdir(exist_ok=True)
    yaml_text = gen_yaml(findings)
    out.write_text(yaml_text)
    print(f"[axiom init] Written to {out}")
    print()
    print(yaml_text)
