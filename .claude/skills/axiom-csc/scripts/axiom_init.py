#!/usr/bin/env python3
# axiom init - Zero-touch invariants discovery.
# Scans workspace, generates .axiom/invariants.yaml automatically.
import pathlib, re, sys

SCAN_EXT = {".py", ".ts", ".js", ".yaml", ".yml", ".json", ".env", ".toml", ".cfg"}
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "dist", "build", ".claude"}

HEURISTICS = [
    ("transaction_value",  "payments",      r'(?:max|limit|cap).*?(?:amount|price|cost|invoice)[^\n]*?(\d[\d,]*(?:\.\d{2})?)', "max", 10000, "BLOCK"),
    ("rate_limit_rpm",     "rate_limiting", r'(?:rate.?limit|throttle|rpm)[^\n]*?(\d+)',                                        "max", 1000,  "BLOCK"),
    ("file_size_mb",       "file_uploads",  r'(?:max.?(?:file)?size|upload.?limit)[^\n]*?(\d+)\s*MB',                          "max", 100,   "BLOCK"),
    ("query_row_limit",    "database",      r'(?:LIMIT|row.?limit|max.?rows?)[^\n\s]*\s*(\d+)',                                 "max", 10000, "ASK"),
    ("api_quota_daily",    "api",           r'(?:daily.?(?:quota|limit)|calls?.?per.?day)[^\n]*?(\d+)',                         "max", 10000, "ASK"),
    ("timeout_seconds",    "api",           r'(?:timeout|TTL)[^\n]*?(\d+)\s*s',                                                 "max", 30,    "ASK"),
    ("retry_count",        "api",           r'(?:max.?retries?|retry.?count)[^\n]*?(\d+)',                                      "max", 5,     "BLOCK"),
]

def scan(root):
    findings = {}
    for path in pathlib.Path(root).rglob("*"):
        if not path.is_file(): continue
        if path.suffix not in SCAN_EXT: continue
        if any(d in path.parts for d in SKIP_DIRS): continue
        try: text = path.read_text(errors="ignore")
        except: continue
        for concept, domain, pattern, bkey, default, action in HEURISTICS:
            if concept in findings: continue
            m = re.search(pattern, text, re.IGNORECASE)
            if m:
                try: val = float(m.group(1).replace(",", ""))
                except: val = default
                findings[concept] = {"domain": domain, "value": val, "source": str(path.relative_to(root)), "action": action}
    return findings

def gen_yaml(findings):
    lines = [
        "# .axiom/invariants.yaml - generated by axiom init",
        "# Edit values to match your project's actual limits.",
        "# Supported ops: lte, gte, lt, gt, eq",
        "rules:",
    ]
    for concept, info in findings.items():
        if info["value"] is None or info["action"] == "ASK":
            lines.append(f"  # source: {info.get('source', 'default')}")
            lines.append(f"  - concept: {concept}")
            lines.append(f"    required: true")
            lines.append(f"    action_on_missing: ASK")
        else:
            lines.append(f"  # source: {info.get('source', 'default')}")
            lines.append(f"  - concept: {concept}")
            lines.append(f"    op: lte")
            lines.append(f"    value: {info['value']}")
            lines.append(f"    action_on_fail: BLOCK")
        lines.append("")
    # Security rules — always active
    lines += [
        "  # Security rules — always active",
        "  - concept: dangerous_bash",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: secret_pattern",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: auth_hardcoded_id",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: auth_uncond_return",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: auth_role_literal",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: auth_commented_check",
        "    banned: true",
        "    action_on_fail: BLOCK",
        "  - concept: dep_confusion",
        "    banned: true",
        "    action_on_fail: BLOCK",
    ]
    return "\n".join(lines)

if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    print(f"[axiom init] Scanning {pathlib.Path(root).resolve()} ...")
    findings = scan(root)
    print(f"[axiom init] Signals: {list(findings.keys())} + auth (always)")
    out = pathlib.Path(root) / ".axiom" / "invariants.yaml"
    out.parent.mkdir(exist_ok=True)
    yaml_text = gen_yaml(findings)
    out.write_text(yaml_text)
    print(f"[axiom init] Written to {out}")

    # Add axiom runtime files to .gitignore so local logs and state never get committed
    gitignore = pathlib.Path(root) / ".gitignore"
    axiom_entries = [".axiom/local_log.jsonl", ".axiom/audit.log", ".axiom/ast.json", ".axiom/state.json"]
    existing = gitignore.read_text() if gitignore.exists() else ""
    new_entries = [e for e in axiom_entries if e not in existing]
    if new_entries:
        with open(gitignore, "a") as f:
            f.write("\n# axiom-csc runtime files\n")
            for e in new_entries:
                f.write(e + "\n")
        print(f"[axiom init] Added {len(new_entries)} entries to .gitignore")

    print()
    print(yaml_text)
